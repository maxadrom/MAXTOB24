-- Сессии Открытой линии на привязке (M25). Клиент каждой сессии ОЛ — автор её
-- первого сообщения, поэтому новую сессию открывает служебное сообщение от
-- псевдо-пользователя «группа» (опенер). Об окончании сессии Б24 сообщает
-- событием OnImConnectorDialogFinish; слать опенер сразу нельзя — сообщение в
-- закрытую сессию создаст новую пустую. Поэтому событие только взводит флаг, а
-- опенер уходит перед следующим входящим из MAX.
--   ol_session_id        — последняя известная сессия (ответ send.messages,
--                          событие Finish). Растёт монотонно: устаревший Finish
--                          (входящее уже открыло новую сессию) флаг не взводит.
--   ol_closed_session_id — сессия, закрытая по Finish. Не NULL = перед следующим
--                          входящим нужен опенер.
-- integer: id сессии в Б24 — int; bigint драйвер pg отдал бы строкой.
-- Бэкфилла нет: NULL = сессия неизвестна, опенер не нужен (поведение до M25).
-- Деплой поднимает код раньше миграции: ChatBinding.fromRow без этих колонок
-- считает их NULL, а запись сессии — best-effort.

ALTER TABLE chat_bindings ADD COLUMN IF NOT EXISTS ol_session_id integer;
ALTER TABLE chat_bindings ADD COLUMN IF NOT EXISTS ol_closed_session_id integer;
